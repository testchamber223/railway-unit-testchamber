"""Verification of core/rom.py with MANUFACTURED "CFD" data (verification-only).

The "CFD results" are generated by the multi-zone model itself with known
parameters plus small seeded noise. They are NOT Fluent results.
"""

import numpy as np
import pandas as pd
import pytest

from core import psychro
from core.coach import MultiZoneCoach, SingleZoneCoach, load_coach_definition
from core.procedures import run_procedure
from core.rom import ROMSetup, ValidityRange, calibrate, lhs_design, leave_one_out, write_run_list
from core.unit import load_unit_card
from tests.conftest import DATA, verification_registry

BASE = SingleZoneCoach("verification", 300.0, 1.2, 5e6, air_volume_m3=150.0)
SETUP = ROMSetup(MultiZoneCoach(BASE, return_weight=(0.0, 0.0, 1.0),
                                solar_share=(0.2, 0.3, 0.5)),
                 supply_T_C=14.0, supply_W=psychro.humidity_ratio(14.0, 0.8),
                 pax_sensible_W=70.0)
FACTORS = {"supply_airflow_m3_h": (3000.0, 6000.0), "outside_T_C": (25.0, 45.0),
           "solar_W_m2": (0.0, 800.0), "occupancy": (0.0, 80.0)}
TRUE = SETUP.theta(300.0, (0.40, 0.35, 0.25), 20.0)
START = SETUP.theta(100.0, (1 / 3, 1 / 3, 1 / 3), 10.0)
DESIGN = lhs_design(FACTORS, 12, seed=1)


def manufactured(noise=0.0, seed=7):
    rng = np.random.default_rng(seed)
    return SETUP.predict_all(TRUE, DESIGN) + rng.normal(0.0, noise, (len(DESIGN), SETUP.n))


def test_latin_hypercube_is_stratified():
    assert list(DESIGN.columns) == ["run_id", *FACTORS]
    for name, (lo, hi) in FACTORS.items():
        bins = np.floor((DESIGN[name] - lo) / (hi - lo) * len(DESIGN)).astype(int)
        assert sorted(bins) == list(range(len(DESIGN)))         # one sample per stratum


def test_run_list_csv(tmp_path):
    path = write_run_list(DESIGN, tmp_path / "runs.csv", {"supply_T_C": 14.0})
    back = pd.read_csv(path)
    assert list(back["run_id"]) == list(DESIGN["run_id"])
    assert (back["supply_T_C"] == 14.0).all()
    assert np.allclose(back["outside_T_C"], DESIGN["outside_T_C"], rtol=1e-5)


def test_noise_free_calibration_recovers_parameters_exactly():
    cal = calibrate(SETUP, DESIGN, manufactured(0.0), START)
    assert cal.success
    assert np.allclose(cal.theta, TRUE, rtol=1e-6, atol=1e-8)
    assert max(cal.rms.values()) < 1e-6


def test_noisy_calibration_recovers_parameters_within_tolerance():
    cal = calibrate(SETUP, DESIGN, manufactured(0.02), START)
    p = cal.parameters
    assert p["G_mix_W_K"] == pytest.approx(300.0, rel=0.10)
    assert np.allclose(p["supply_fraction"], (0.40, 0.35, 0.25), atol=0.01)
    assert p["A_sol_m2"] == pytest.approx(20.0, rel=0.02)
    assert set(cal.rms) == {"T_front", "T_middle", "T_back", "spread"}
    assert all(r < 0.03 for r in cal.rms.values())             # ~ noise level
    assert all(cal.max_abs[k] >= cal.rms[k] for k in cal.rms)


def test_leave_one_out():
    loo = leave_one_out(SETUP, DESIGN, manufactured(0.02), START)
    assert list(loo["run_id"]) == list(DESIGN["run_id"])
    assert {"err_T_front", "err_T_middle", "err_T_back", "err_spread"} <= set(loo.columns)
    assert loo["max_abs_err"].max() < 0.15


def test_validity_range_is_the_design_bounding_box():
    vr = ValidityRange.from_design(DESIGN)
    for name in FACTORS:
        assert vr.bounds[name] == (DESIGN[name].min(), DESIGN[name].max())
    inside = {k: (lo + hi) / 2 for k, (lo, hi) in vr.bounds.items()}
    assert vr.check(inside) == []
    w = vr.check({**inside, "outside_T_C": 50.0})
    assert len(w) == 1 and "outside_T_C = 50" in w[0] and "outside the calibrated range" in w[0]


def test_procedure_outside_the_validity_range_gets_a_warning():
    reg = verification_registry()
    coach = load_coach_definition(evidence=reg)
    card = load_unit_card(DATA / "verification_unit.yaml")
    narrow = ValidityRange({"outside_T_C": (25.0, 40.0), "solar_W_m2": (0.0, 900.0),
                            "occupancy": (0.0, 100.0), "supply_airflow_m3_h": (3000.0, 7000.0)})
    res = run_procedure("comfort_en13129_zone1", coach=coach, unit_card=card, evidence=reg,
                        rom_validity=narrow)                   # chamber at 45 degC
    assert len(res.warnings) == 1 and "outside_T_C = 45" in res.warnings[0]
    assert "Warnings:" in res.summary()
    wide = ValidityRange({**narrow.bounds, "outside_T_C": (25.0, 50.0)})
    res = run_procedure("comfort_en13129_zone1", coach=coach, unit_card=card, evidence=reg,
                        rom_validity=wide)
    assert res.warnings == []
